package Concepts.Basics;

public class Variables {
    public static void main(String[] args) {
        int a = 10;  // declaration and initialization of variable a

        System.out.print(a +23);


        int y;  // declaration of variable y
        y = 34;  // initialization of variable y
        System.out.println(y);
        
        int x = 45, z = 56;  // declaration and initialization of variables x and z
        
        System.out.println(x +z);
        int p = 556;
        System.out.println(p);
        p = 78;
        p+= 22;  // p = p + 22
        p*=56;  // p = p * 56
        p/= 100;  // p = p / 100
        System.out.println(p);

    // Area of a Circ
    double r = 3.8;
    double area = 3.141592 * r * r;
    System.out.println("Area of the circle is: " + area);

    // Volume of a Sphere
    double volume = (4.0/3.0)*3.141592*r*r*r;
    System.out.println("Volume of the sphere is: " + volume);
    

    int Guddu = 100;
    int Bablu = 200;
    int TotalMoney = Guddu + Bablu;
    System.out.println("Total Money on Guddu and Bablu : " + TotalMoney);
    /*
    Multiline comment
    */
}
    
}
